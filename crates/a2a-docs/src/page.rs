//! What every generated page shares: its front matter, its header line, links into the repository
//! and Markdown escaping.

/// The first line of every generated page's front matter.
pub const FRONT_MATTER_HEADER: &str = "# generated by a2a-docs, do not edit";
/// The line every generated page carries directly after its front matter.
pub const HEADER: &str = "<!-- generated by a2a-docs, do not edit -->";
/// The repository on GitHub.
pub const REPOSITORY: &str = "https://github.com/beyond10x/a2a";
/// A file in the repository on GitHub, by path.
pub const SOURCE: &str = "https://github.com/beyond10x/a2a/blob/main";
/// The path the site is served under, as `docusaurus.config.ts` sets `baseUrl`.
pub const BASE_URL: &str = "/a2a/";

/// What the front matter of one generated page says.
pub struct Meta<'a> {
    pub title: &'a str,
    pub label: &'a str,
    pub description: &'a str,
    pub position: Option<u32>,
}

fn yaml_string(value: &str) -> String {
    format!("\"{}\"", value.replace('\\', "\\\\").replace('"', "\\\""))
}

/// The front matter of a generated page (the generator line, title, label, an optional sidebar
/// position, description, and no edit link), then [`HEADER`].
pub fn front_matter(meta: &Meta<'_>) -> String {
    let position = meta
        .position
        .map(|n| format!("sidebar_position: {n}\n"))
        .unwrap_or_default();
    format!(
        "---\n{FRONT_MATTER_HEADER}\ntitle: {}\nsidebar_label: {}\n{position}description: {}\ncustom_edit_url: null\n---\n\n{HEADER}\n\n",
        yaml_string(meta.title),
        yaml_string(meta.label),
        yaml_string(
            &meta
                .description
                .split_whitespace()
                .collect::<Vec<_>>()
                .join(" ")
        ),
    )
}

/// `text` with every character Markdown would read as syntax escaped.
fn escape(text: &str, backticks: bool) -> String {
    let mut out = String::with_capacity(text.len());
    for c in text.chars() {
        match c {
            '\\' | '*' | '_' | '[' | ']' | '|' | '<' | '>' | '&' | '~' => {
                out.push('\\');
                out.push(c);
            }
            '`' if backticks => out.push_str("\\`"),
            _ => out.push(c),
        }
    }
    out
}

/// `text` on one line as inline Markdown that is safe in a table cell: its code spans are kept
/// (with `|` escaped), everything else is escaped. Text whose backticks do not pair is escaped
/// whole.
pub fn inline(text: &str) -> String {
    let text = text.split_whitespace().collect::<Vec<_>>().join(" ");
    let segments: Vec<&str> = text.split('`').collect();
    if segments.len().is_multiple_of(2) {
        return escape(&text, true);
    }
    segments
        .iter()
        .enumerate()
        .map(|(n, segment)| {
            if n % 2 == 1 {
                format!("`{}`", segment.replace('|', "\\|"))
            } else {
                escape(segment, false)
            }
        })
        .collect()
}

/// `text` as a code span, safe in a table cell.
pub fn code(text: &str) -> String {
    format!("`{}`", text.replace('|', "\\|"))
}

/// A link to `path` in the repository, shown as code.
pub fn source_link(path: &str) -> String {
    format!("[{}]({SOURCE}/{path})", code(path))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn front_matter_opens_with_the_generator_line_and_has_no_edit_link() {
        let page = front_matter(&Meta {
            title: "HTTP+JSON \"routes\"",
            label: "HTTP routes",
            description: "Two\n  lines.",
            position: Some(2),
        });
        assert_eq!(
            page,
            "---\n# generated by a2a-docs, do not edit\ntitle: \"HTTP+JSON \\\"routes\\\"\"\nsidebar_label: \"HTTP routes\"\nsidebar_position: 2\ndescription: \"Two lines.\"\ncustom_edit_url: null\n---\n\n<!-- generated by a2a-docs, do not edit -->\n\n"
        );
    }

    #[test]
    fn inline_keeps_code_spans_and_escapes_the_rest() {
        assert_eq!(
            inline("Optional<String> `a|b` [x] *y*_z"),
            "Optional\\<String\\> `a\\|b` \\[x\\] \\*y\\*\\_z"
        );
        assert_eq!(inline("one ` unpaired"), "one \\` unpaired");
        assert_eq!(inline("two\n   lines"), "two lines");
    }
}
