//! Adversary cases for `a2a-docs` (story:docs-site).
//!
//! The acceptance asks for generated reference pages that `task check` holds to the repository,
//! and AGENTS.md names `website/docs/reference/` as written by `task docs-generate`, with
//! `task docs-check` failing "on a missing, stale or hand-edited one". Each case copies the
//! inputs `a2a-docs generate --check` reads into a scratch root, plants one change, and runs the
//! binary there. The control case runs it on the unchanged copy, so a red case is red because of
//! its plant.

use std::{
    fs,
    path::{Path, PathBuf},
    process::{Command, Output},
};

/// What `generate --check` reads or compares, relative to the repository root.
const INPUTS: [&str; 7] = [
    "ess",
    "upstream",
    "generated/openapi",
    "generated/openapi-http",
    "generated/asyncapi",
    "generated/schema",
    "CHANGELOG.md",
];
/// What `generate --check` holds to the inputs.
const OUTPUTS: [&str; 2] = ["website/docs/reference", "website/static/downloads"];

fn root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .ancestors()
        .nth(2)
        .unwrap()
        .to_path_buf()
}

fn copy(from: &Path, to: &Path) {
    if from.is_dir() {
        fs::create_dir_all(to).unwrap();
        for entry in fs::read_dir(from).unwrap() {
            let entry = entry.unwrap();
            copy(&entry.path(), &to.join(entry.file_name()));
        }
    } else {
        fs::create_dir_all(to.parent().unwrap()).unwrap();
        fs::copy(from, to).unwrap();
    }
}

/// A scratch copy of the repository's inputs and generated site files.
fn scratch(name: &str) -> PathBuf {
    let dir = Path::new(env!("CARGO_TARGET_TMPDIR"))
        .join("adv-docs-site")
        .join(format!("{name}-{}", std::process::id()));
    let _ = fs::remove_dir_all(&dir);
    for path in INPUTS.iter().chain(OUTPUTS.iter()) {
        copy(&root().join(path), &dir.join(path));
    }
    dir
}

fn check(dir: &Path) -> Output {
    Command::new(env!("CARGO_BIN_EXE_a2a-docs"))
        .env("CARGO_TARGET_DIR", dir.join("target"))
        .args(["generate", "--check", "--root"])
        .arg(dir)
        .output()
        .unwrap()
}

#[test]
fn control_the_committed_site_passes_the_check() {
    let dir = scratch("control");
    let out = check(&dir);
    assert!(
        out.status.success(),
        "{}",
        String::from_utf8_lossy(&out.stderr)
    );
    fs::remove_dir_all(dir).unwrap();
}

/// A page under `website/docs/reference/` that `a2a-docs` does not generate (a page a later
/// generator renamed or dropped, or one added by hand) is published under Reference by the
/// autogenerated sidebar. AGENTS.md says the directory is `task docs-generate`'s and that
/// `task docs-check` fails on a hand-edited file there; the check never looks.
#[test]
fn a_page_in_reference_that_a2a_docs_does_not_generate_fails_the_check() {
    let dir = scratch("stray-reference");
    fs::write(
        dir.join("website/docs/reference/routes.md"),
        "---\ntitle: \"HTTP routes (old)\"\n---\n\nA page a2a-docs no longer writes.\n",
    )
    .unwrap();
    let out = check(&dir);
    let stderr = String::from_utf8_lossy(&out.stderr).into_owned();
    fs::remove_dir_all(dir).unwrap();
    assert!(
        !out.status.success(),
        "generate --check passed with website/docs/reference/routes.md, which it does not \
         generate; stdout: {}",
        String::from_utf8_lossy(&out.stdout)
    );
    assert!(stderr.contains("routes.md"), "{stderr}");
}

/// Each download is the repository file its name says, as a literal pair. The crate's own test
/// compares each download with the source its table names, so exchanging two sources in that
/// table passes it, and passes `generate --check` after `task docs-generate`.
#[test]
fn each_download_is_the_repository_file_its_name_says() {
    let pairs = [
        ("a2a.proto", "upstream/a2a.proto"),
        (
            "a2a-upstream.openapi.yaml",
            "upstream/openapi/a2a.openapi.yaml",
        ),
        (
            "a2a-http.openapi.yaml",
            "generated/openapi-http/openapi/a2a-agent.yaml",
        ),
        (
            "a2a.openapi.yaml",
            "generated/openapi/openapi/a2a-agent.yaml",
        ),
        (
            "a2a.asyncapi.yaml",
            "generated/asyncapi/asyncapi/a2a-agent.yaml",
        ),
    ];
    for (download, source) in pairs {
        let served = fs::read(root().join("website/static/downloads").join(download)).unwrap();
        assert!(
            served == fs::read(root().join(source)).unwrap(),
            "website/static/downloads/{download} is not {source}"
        );
    }
}
